def rsm_panel_3d(ax, xvar, yvar, fixed_var, fixed_val, panel_label, vmin, vmax):
    XX, YY, Z = eval_surface("Photodeg_pct", xvar, yvar, fixed_var, fixed_val, n=60)
    Zf = Z.filled(np.nan)
    floor = vmin - 0.35*(vmax-vmin)
    surf = ax.plot_surface(XX, YY, Zf, cmap=BLUE_CMAP, vmin=vmin, vmax=vmax, linewidth=0.15,
                            edgecolor="white", antialiased=True, rstride=1, cstride=1, alpha=0.98, zorder=1)
    ax.contour(XX, YY, Zf, levels=np.linspace(vmin, vmax, 8), cmap=BLUE_CMAP, offset=floor, linewidths=0.6, alpha=0.6, zorder=0)
    sel = np.isclose(core.bbd[fixed_var], fixed_val, atol=1e-6)
    xs_, ys_, zs_ = core.bbd.loc[sel, xvar].values, core.bbd.loc[sel, yvar].values, core.bbd.loc[sel, "Photodeg_pct"].values
    ax.scatter(xs_, ys_, zs_, s=34, color="white", edgecolor=INK, linewidth=0.9, depthshade=False, zorder=10)
    for xp, yp, zp in zip(xs_, ys_, zs_):
        ax.plot([xp,xp],[yp,yp],[floor,zp], color=BASE, linewidth=0.6, linestyle=":", zorder=2)
    ax.set_xlabel(AX_LABEL[xvar], fontsize=6.6, labelpad=5); ax.set_ylabel(AX_LABEL[yvar], fontsize=6.6, labelpad=5)
    letter = panel_label.split(")")[0] + ")"
    ax.set_title(letter, fontsize=9, fontweight="bold", loc="center", y=0.98)
    ax.set_xlim(BOUNDS[xvar]); ax.set_ylim(BOUNDS[yvar]); ax.set_zlim(floor, vmax)
    ax.view_init(elev=26, azim=-125); ax.tick_params(labelsize=5.8, pad=0)
    for pane in (ax.xaxis.pane, ax.yaxis.pane, ax.zaxis.pane):
        pane.set_facecolor("white"); pane.set_edgecolor(BASE); pane.set_alpha(1.0)
    ax.zaxis.pane.set_facecolor("#f4f3ef")
    ax.grid(False)
    return surf

