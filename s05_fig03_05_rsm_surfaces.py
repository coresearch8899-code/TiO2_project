def eval_surface(resp, xvar, yvar, fixed_var, fixed_val, n=220):
    lo_x, hi_x = BOUNDS[xvar]; lo_y, hi_y = BOUNDS[yvar]
    xs = np.linspace(lo_x, hi_x, n); ys = np.linspace(lo_y, hi_y, n)
    XX, YY = np.meshgrid(xs, ys)
    coords = {xvar: XX, yvar: YY, fixed_var: np.full_like(XX, fixed_val)}
    g_flat, c_flat, t_flat = coords["Glucose_g"].ravel(), coords["CuSO4_g"].ravel(), coords["Time_min"].ravel()
    Z = core.rsm_predict(resp, g_flat, c_flat, t_flat).reshape(XX.shape)
    norm = core.coded_norm(g_flat, c_flat, t_flat).reshape(XX.shape)
    Z = np.ma.array(Z, mask=(norm > core.BBD_SUPPORT_RADIUS))
    return XX, YY, Z

def rsm_panel(ax, resp, cmap, xvar, yvar, fixed_var, fixed_val, panel_label, vmin, vmax, unit_fmt="%.0f"):
    XX, YY, Z = eval_surface(resp, xvar, yvar, fixed_var, fixed_val)
    ax.set_facecolor("#eceae2")
    cf = ax.contourf(XX, YY, Z, levels=np.linspace(vmin, vmax, 15), cmap=cmap, vmin=vmin, vmax=vmax, extend="both")
    cs = ax.contour(XX, YY, Z, levels=np.linspace(vmin, vmax, 8), colors=INK2, linewidths=0.5, alpha=0.7)
    ax.clabel(cs, inline=True, fontsize=6, fmt=unit_fmt)
    sel = np.isclose(core.bbd[fixed_var], fixed_val, atol=1e-6)
    ax.scatter(core.bbd.loc[sel, xvar], core.bbd.loc[sel, yvar], s=32, facecolor="white",
               edgecolor=INK, linewidth=0.9, zorder=5)
    ax.set_xlabel(AX_LABEL[xvar]); ax.set_ylabel(AX_LABEL[yvar])
    letter = panel_label.split(")")[0] + ")"
    ax.set_title(letter, loc="center", fontsize=9, fontweight="bold", color=INK)
    ax.set_xlim(BOUNDS[xvar]); ax.set_ylim(BOUNDS[yvar])
    return cf

